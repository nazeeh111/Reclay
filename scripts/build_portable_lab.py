"""Export the actual learned editor and independently produced controls."""

import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from reclay.relocation import infer_relocation, export_relocation

EX = ROOT / "reclay/examples/relocation"
manifest = json.loads((EX / "manifest.json").read_text())
samples = manifest["training"]
answer = infer_relocation(
    [(EX / x["name"]).read_bytes() for x in samples],
    [[x["start"], x["end"]] for x in samples],
)
assert answer["status"] == "unique" and not answer["truncated"]
model = answer["models"][0]
files = {
    "editor.py": export_relocation(model).encode(),
    "model.json": (json.dumps(model, indent=2) + "\n").encode(),
    "LICENSE": (ROOT / "LICENSE").read_bytes(),
    "manifest.json": (EX / "manifest.json").read_bytes(),
}
files["README.txt"] = b"""Reclay 0.3 portable relocation experiment

Python 3.10+, standard library only. No installation or server needed.

python3 -I -S editor.py inspect working.tif --start 146 --end 194
python3 -I -S editor.py rebuild working.tif replacement-1.bin edited.tif --start 146 --end 194

Compare edited.tif with oracle-1.tif using your system's byte comparison.
The oracle was separately generated by Pillow, not by the exported editor.
Try the other replacement files to exercise shrink, parity and >64KiB growth.
Existing output files are never overwritten; choose a new name each time.

This model guards one document family with identical untouched pixels and
metadata. It refuses spans below the smallest observed length (5 bytes),
changed topology/literal bytes and invalid learned fields. These conditions
do not establish complete format semantics or arbitrary TIFF editing.
Pointer inference has prior work; this is a guarded observation-to-editor
workflow, not universal lost-software reconstruction. Images and metadata
are owned synthetic content, independently produced using Pillow12.3.0.
Source, actual studio, producer and validation:
https://github.com/nazeeh111/Reclay
"""
for entry in [manifest["working"]["name"]] + [
    case[k] for case in manifest["heldout"] for k in ("payload", "oracle")
]:
    files[entry] = (EX / entry).read_bytes()
records = [
    {"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    for name, data in sorted(files.items())
]
files["bundle-manifest.json"] = (
    json.dumps({"modelId": model["id"], "files": records}, indent=2) + "\n"
).encode()
out = ROOT / "dist"
out.mkdir(exist_ok=True)
target = out / "reclay-relocation-lab-0.3.0.zip"
with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
    for name, data in sorted(files.items()):
        info = zipfile.ZipInfo(name, (2026, 10, 13, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        archive.writestr(info, data)
print(
    json.dumps(
        {
            "zip": str(target),
            "members": len(files),
            "modelId": model["id"],
            "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
        }
    )
)
